def calc_crc8(data: bytes) -> int:
    """计算 CRC8-Maxim 校验码"""
    r = 0
    for b in data:
        r = CRC8_TABLE[r ^ b]
    return r

def build_packet(cmd: int, payload: Optional[List[int]] = None) -> bytes:
    """
    构造标准指令报文
    格式: [0xFC, 0xFA, LENGTH, CMD, PAYLOAD..., CRC8]
    """
    if payload is None:
        payload = []
    pkt = bytes([0xFC, 0xFA, len(payload), cmd]) + bytes(payload)
    crc = calc_crc8(pkt)
    return pkt + bytes([crc])

def parse_notify_packet(data: bytes) -> Optional[Tuple[int, bytes]]:
    """
    解析来自耳机的 Notify 报文
    返回: (cmd, payload) 或 None
    """
    if len(data) < 5 or data[0] != 0xFC or data[1] != 0xFA:
        return None
    length = data[2]
    cmd = data[3]
    payload = data[4:4 + length]
    # 校验 CRC8
    expected_crc = calc_crc8(data[:-1])
    if data[-1] != expected_crc:
        return None
    return cmd, payload

def parse_battery(payload: bytes) -> str:
    """
    解析 0x74 电量数据包
    官方格式: [左耳在线标志, 左耳电量, 右耳在线标志, 右耳电量, ...]
    """
    if not payload:
        return "--"

    b0 = payload[0] if len(payload) > 0 else 0
    b1 = payload[1] if len(payload) > 1 else 0
    b2 = payload[2] if len(payload) > 2 else 0
    b3 = payload[3] if len(payload) > 3 else 0

    left_val = b1 if (b0 and b1 not in (0, 255) and 0 < b1 <= 100) else None
    right_val = b3 if (b2 and b3 not in (0, 255) and 0 < b3 <= 100) else None

    if left_val is not None and right_val is not None:
        return f"{left_val}%" if left_val == right_val else f"L:{left_val}% R:{right_val}%"
    elif left_val is not None:
        return f"{left_val}%"
    elif right_val is not None:
        return f"{right_val}%"
    elif len(payload) == 1 and 0 < payload[0] <= 100:
        return f"{payload[0]}%"
    
    # 兜底查找首个合法百分比
    for b in payload:
        if 1 < b <= 100 and b != 255:
            return f"{b}%"

    return "--"
